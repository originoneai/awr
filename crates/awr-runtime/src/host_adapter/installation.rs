//! Project-local lifecycle configuration and receiver observations.
use awr_core::{Error, Id, Result};
use awr_source::{GatePolicy, WriteGate};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    collections::BTreeSet,
    fs,
    io::Write,
    path::{Path, PathBuf},
};

pub const ADAPTER_VERSION: u64 = 1;
pub const CLAUDE_WRITE_MATCHER: &str = "Edit|Write|MultiEdit|NotebookEdit";

pub fn configuration_paths(client: &str) -> Result<&'static [&'static str]> {
    match client {
        "codex" => Ok(&[".codex/hooks.json"]),
        "claude" => Ok(&[".claude/settings.local.json", ".claude/settings.json"]),
        _ => Err(Error::Unsupported("project lifecycle installation supports codex and claude; other hosts use the generic receiver and manual checkpoints".into())),
    }
}

/// Read exact project paths, refusing both directory and file symlinks.
pub fn read_configuration(path: &Path) -> Result<Option<Vec<u8>>> {
    if let Some(parent) = path.parent() {
        match fs::symlink_metadata(parent) {
            Ok(_) => {
                awr_source::open_dir_exact(parent)?;
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(e.into()),
        }
    }
    match fs::symlink_metadata(path) {
        Ok(_) => awr_source::read_source_capped(path, 1024 * 1024).map(Some),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}

pub fn parse_configuration(bytes: Option<&[u8]>) -> Result<Value> {
    let value = bytes.map(serde_json::from_slice).transpose()
        .map_err(|_| Error::InvalidInput("existing hook configuration must be valid JSON; preserve and fix it before installation".into()))?
        .unwrap_or_else(|| serde_json::json!({}));
    if !value.is_object() || value.get("hooks").is_some_and(|v| !v.is_object()) {
        return Err(Error::InvalidInput(
            "hook configuration and its hooks field must be objects".into(),
        ));
    }
    if let Some(hooks) = value["hooks"].as_object() {
        if hooks.values().any(|v| !v.is_array()) {
            return Err(Error::InvalidInput(
                "hook event handlers must be arrays".into(),
            ));
        }
        for groups in hooks.values() {
            if groups.as_array().unwrap().iter().any(|group| {
                !group.is_object() || group.get("hooks").is_some_and(|hooks| !hooks.is_array())
            }) {
                return Err(Error::InvalidInput(
                    "hook groups must be objects with hook arrays".into(),
                ));
            }
        }
    }
    Ok(value)
}

/// Tokenize the quoted command forms generated by the two installers. This is
/// inspection only: configuration commands are never executed to infer ownership.
fn command_words(command: &str) -> Option<Vec<String>> {
    let mut words = vec![];
    let mut word = String::new();
    let mut quote = None;
    let mut chars = command.chars().peekable();
    while let Some(c) = chars.next() {
        match (quote, c) {
            (Some('\''), '\'') if cfg!(windows) && chars.peek() == Some(&'\'') => {
                chars.next();
                word.push('\'');
            }
            (Some(q), c) if q == c => quote = None,
            (None, '\'' | '"') => quote = Some(c),
            (None, c) if c.is_whitespace() => {
                if !word.is_empty() {
                    words.push(std::mem::take(&mut word));
                }
            }
            (None, '\\') if !cfg!(windows) => word.push(chars.next()?),
            (None, ';' | '|' | '>' | '<' | '`') => return None,
            _ => word.push(c),
        }
    }
    if quote.is_some() {
        return None;
    }
    if !word.is_empty() {
        words.push(word);
    }
    Some(words)
}

#[derive(Debug)]
pub struct ManagedHook {
    pub program: String,
    pub version: Option<u64>,
    pub legacy_work: bool,
}

pub fn managed_hook(hook: &Value, client: &str) -> Option<ManagedHook> {
    if hook["type"] != "command" {
        return None;
    }
    let mut words = command_words(hook["command"].as_str()?)?;
    if words.first().is_some_and(|s| s == "&") {
        words.remove(0);
    }
    let program = words.first()?.clone();
    let name = program.rsplit(['/', '\\']).next()?;
    if !matches!(name, "awr" | "awr.exe") {
        return None;
    }
    let position = words
        .windows(4)
        .position(|v| v == ["client", "hook", "--client", client])?;
    let args = &words[position + 4..];
    // Extra shell actions and user extensions are not installer-owned commands.
    if !args.chunks_exact(2).remainder().is_empty()
        || args
            .chunks_exact(2)
            .any(|pair| !matches!(pair[0].as_str(), "--adapter-version" | "--work"))
    {
        return None;
    }
    let version = args
        .windows(2)
        .find(|v| v[0] == "--adapter-version")
        .and_then(|v| v[1].parse().ok());
    let legacy_work = args.windows(2).any(|v| v[0] == "--work");
    if version.is_none() && !(client == "codex" && legacy_work) {
        return None;
    }
    Some(ManagedHook {
        program,
        version,
        legacy_work,
    })
}

#[derive(Debug, Serialize)]
pub struct HostAdapterStatus {
    pub client: String,
    pub installed: bool,
    pub paths: Vec<PathBuf>,
    pub adapter_version: Option<u64>,
    pub outdated: bool,
    pub program_exists: bool,
    pub events: BTreeSet<String>,
    pub gates_consistent: bool,
    pub write_gate: String,
    pub completion_reminder: bool,
    pub activation: String,
    pub observed_at: Option<i64>,
    pub observed_adapter_version: Option<u64>,
}

fn program_exists(root: &Path, program: &str) -> bool {
    if Path::new(program).is_absolute() {
        return Path::new(program).is_file();
    }
    if program.contains(['/', '\\']) {
        return root.join(program).is_file();
    }
    std::env::var_os("PATH").is_some_and(|path| {
        std::env::split_paths(&path).any(|dir| {
            dir.join(program).is_file()
                || cfg!(windows) && dir.join(format!("{program}.exe")).is_file()
        })
    })
}

pub fn inspect_host_adapters(
    root: &Path,
    selected: Option<&str>,
) -> Result<Vec<HostAdapterStatus>> {
    if let Some(client) = selected {
        configuration_paths(client)?;
    }
    let policy = GatePolicy::load(root)?.hooks;
    let write_on = policy.write_gate != WriteGate::Off;
    let mut statuses = vec![];
    for client in ["codex", "claude"] {
        if selected.is_some_and(|selected| selected != client) {
            continue;
        }
        let mut status = HostAdapterStatus {
            client: client.into(),
            installed: false,
            paths: vec![],
            adapter_version: None,
            outdated: false,
            program_exists: true,
            events: BTreeSet::new(),
            gates_consistent: true,
            write_gate: format!("{:?}", policy.write_gate).to_lowercase(),
            completion_reminder: policy.completion_reminder,
            activation: "not observed".into(),
            observed_at: None,
            observed_adapter_version: None,
        };
        for relative in configuration_paths(client)? {
            let path = root.join(relative);
            let bytes = read_configuration(&path)?;
            let config = parse_configuration(bytes.as_deref())?;
            let mut installed_here = false;
            if let Some(hooks) = config["hooks"].as_object() {
                for (event, groups) in hooks {
                    for group in groups.as_array().unwrap() {
                        for hook in group["hooks"].as_array().into_iter().flatten() {
                            if let Some(managed) = managed_hook(hook, client) {
                                installed_here = true;
                                status.events.insert(event.clone());
                                status.outdated |= managed.legacy_work
                                    || managed.version.unwrap_or(0) < ADAPTER_VERSION;
                                status.adapter_version = Some(
                                    status
                                        .adapter_version
                                        .unwrap_or(u64::MAX)
                                        .min(managed.version.unwrap_or(0)),
                                );
                                status.program_exists &= program_exists(root, &managed.program);
                                if client == "claude" && event == "PreToolUse" {
                                    status.gates_consistent &=
                                        group["matcher"] == CLAUDE_WRITE_MATCHER;
                                }
                            }
                        }
                    }
                }
            }
            if installed_here {
                status.paths.push(path);
            }
        }
        status.installed = !status.paths.is_empty();
        status.program_exists &= status.installed;
        status.gates_consistent &= status.installed
            && (status.events.contains("PreToolUse") == write_on)
            && (!policy.completion_reminder || status.events.contains("Stop"));
        if let Some(bytes) = read_configuration(&observation_path(root, client))? {
            let observation: HookObservation = serde_json::from_slice(&bytes)
                .map_err(|_| Error::InvalidInput("invalid hook receiver observation".into()))?;
            status.activation = "observed".into();
            status.observed_at = Some(observation.observed_at);
            status.observed_adapter_version = observation.adapter_version;
        }
        statuses.push(status);
    }
    Ok(statuses)
}

#[derive(Serialize, Deserialize)]
struct HookObservation {
    observed_at: i64,
    adapter_version: Option<u64>,
    event: String,
}
fn observation_path(root: &Path, client: &str) -> PathBuf {
    root.join(".awr/clients")
        .join(format!("adapter-{client}.json"))
}

/// A local receiver receipt, independent of client binding and native activation.
/// Gate decisions keep their existing event stream and read-only database path.
pub fn record_hook_observation(
    root: &Path,
    client: &str,
    version: Option<u64>,
    event: &str,
) -> Result<()> {
    configuration_paths(client)?;
    let path = observation_path(root, client);
    let runtime = awr_source::open_dir_exact(&root.join(".awr"))?;
    if let Err(e) = runtime.create_dir("clients") {
        if e.kind() != std::io::ErrorKind::AlreadyExists {
            return Err(e.into());
        }
    }
    let dir = awr_source::open_dir_exact(path.parent().unwrap())?;
    let temporary = format!("awr-observation-{}.json", Id::new());
    let mut options = cap_std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    let mut file = dir.open_with(&temporary, &options)?;
    let result = (|| -> Result<()> {
        file.write_all(&serde_json::to_vec(&HookObservation {
            observed_at: awr_core::now_millis()?,
            adapter_version: version,
            event: event.into(),
        })?)?;
        file.sync_all()?;
        dir.rename(&temporary, &dir, path.file_name().unwrap())?;
        Ok(())
    })();
    if result.is_err() {
        let _ = dir.remove_file(&temporary);
    }
    result
}
